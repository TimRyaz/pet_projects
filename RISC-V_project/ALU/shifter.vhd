library IEEE;
use IEEE.STD_LOGIC_1164.all;
use IEEE.NUMERIC_STD.all;

entity alu_shifter is
    port(
        A          : in  STD_LOGIC_VECTOR(31 downto 0); -- ??? ????????
        Shamt      : in  STD_LOGIC_VECTOR(4 downto 0);  -- ???????? ?????? (B(4 downto 0))
        ShiftCtrl  : in  STD_LOGIC_VECTOR(1 downto 0);  -- 00: SLL, 01: SRL, 10: SRA
        Result     : out STD_LOGIC_VECTOR(31 downto 0)
    );
end entity;

architecture synth of alu_shifter is
begin

    process(A, Shamt, ShiftCtrl)
        variable shift_val : integer;
    begin
        -- ????????? 5-?????? ???? ? ????? ????? ?? 0 ?? 31
        shift_val := to_integer(unsigned(Shamt));
        
        case ShiftCtrl is
            when "00" => -- SLL (?????????? ?????, ?????? ???????? ????)
                Result <= std_logic_vector(shift_left(unsigned(A), shift_val));
                
            when "01" => -- SRL (?????????? ??????, ????? ???????? ????)
                Result <= std_logic_vector(shift_right(unsigned(A), shift_val));
                
            when "10" => -- SRA (?????????????? ??????, ????? ??????????? ???????? ?[31])
                Result <= std_logic_vector(shift_right(signed(A), shift_val));
                
            when others =>
                Result <= A;
        end case;
    end process;

end architecture;
